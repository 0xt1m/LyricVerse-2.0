const DICTIONARIES: Record<string, Record<string, string>> = { uk, en };

export type Language = "uk" | "en";
export const LANGUAGES: Language[] = ["en", "uk"];
export const LANGUAGE_NAMES: Record<Language, string> = { uk: "Українська", en: "English" };

export function translate(
  language: string,
  key: string,
  values?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[language]?.[key] ?? en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in values ? String(values[name]) : whole,
  );
}

/** Section labels shown to the operator, numbered by order of first use. */
export function sectionLabel(
  language: string,
  kind: string,
  ordinal: number,
  total: number,
): string {
  const names: Record<string, Record<string, string>> = {
    uk: { verse: "Куплет", chorus: "Приспів", bridge: "Брідж", other: "Частина" },
    en: { verse: "Verse", chorus: "Chorus", bridge: "Bridge", other: "Section" },
  };
  const base = names[language]?.[kind] ?? names.en![kind] ?? kind;
  return total > 1 ? `${base} ${ordinal}` : base;
}
